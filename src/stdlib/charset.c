/* --- names ------------------------------------------------------- */

char *cs_java_name(const char *name)
{
    size_t n = strlen(name);
    char *up = AUSSOM_ALLOC_ATOMIC(n + 1);
    for (size_t i = 0; i <= n; i++) {
        char c = name[i];
        if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
        if (c == '_') c = '-';
        up[i] = c;
    }
    return up;
}

static bool is_alnum(char c)
{
    return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9');
}

bool cs_name_legal(const char *name)
{
    if (name[0] == '\0' || !is_alnum(name[0])) return false;
    for (const char *p = name + 1; *p != '\0'; p++) {
        if (!is_alnum(*p) && *p != '-' && *p != '+' && *p != ':' && *p != '_' && *p != '.')
            return false;
    }
    return true;
}

static bool same_icase(const char *a, const char *b)
{
    for (; *a != '\0' && *b != '\0'; a++, b++) {
        char x = *a, y = *b;
        if (x >= 'a' && x <= 'z') x = (char)(x - 'a' + 'A');
        if (y >= 'a' && y <= 'z') y = (char)(y - 'a' + 'A');
        if (x != y) return false;
    }
    return *a == *b;
}

const cs_charset *cs_lookup(const char *name)
{
    for (size_t i = 0; i < sizeof(charsets) / sizeof(charsets[0]); i++) {
        for (const char *const *n = charsets[i].names; *n != NULL; n++) {
            if (same_icase(name, *n)) return &charsets[i];
        }
    }
    return NULL;
}

/* --- UTF-16 unit buffer ------------------------------------------ */

typedef struct { uint16_t *u; size_t n, cap; } units;

static void put_unit(units *b, uint16_t u)
{
    if (b->n == b->cap) {
        size_t cap = b->cap ? b->cap * 2 : 64;
        uint16_t *nu = AUSSOM_ALLOC_ATOMIC(cap * sizeof(uint16_t));
        if (b->n > 0) memcpy(nu, b->u, b->n * sizeof(uint16_t));
        b->u = nu;
        b->cap = cap;
    }
    b->u[b->n++] = u;
}

static void put_cp(units *b, uint32_t cp)
{
    if (cp < 0x10000) {
        put_unit(b, (uint16_t)cp);
    } else {
        cp -= 0x10000;
        put_unit(b, (uint16_t)(0xD800 + (cp >> 10)));
        put_unit(b, (uint16_t)(0xDC00 + (cp & 0x3FF)));
    }
}

static bool is_high(uint32_t u) { return u >= 0xD800 && u <= 0xDBFF; }
static bool is_low(uint32_t u)  { return u >= 0xDC00 && u <= 0xDFFF; }

/* UTF-8 the way new String(bytes, UTF_8) decodes it. Each maximal
 * subpart of an ill-formed sequence (the longest start of a valid
 * sequence, or one byte when even that is invalid) becomes one U+FFFD,
 * the replacement practice the Unicode Standard recommends. Java
 * differs in one place: it reads ED followed by A0-BF and a
 * continuation byte as a complete sequence, then replaces the
 * surrogate it encodes, so those three bytes give one U+FFFD. */
static void utf8_to_units(const unsigned char *d, size_t len, units *out)
{
    size_t i = 0;
    while (i < len) {
        unsigned char c = d[i];
        size_t need;
        unsigned char lo = 0x80, hi = 0xBF;
        if (c < 0x80) { put_unit(out, c); i++; continue; }
        else if (c >= 0xC2 && c <= 0xDF) need = 1;
        else if (c >= 0xE0 && c <= 0xEF) {
            need = 2;
            if (c == 0xE0) lo = 0xA0;
        } else if (c >= 0xF0 && c <= 0xF4) {
            need = 3;
            if (c == 0xF0) lo = 0x90;
            if (c == 0xF4) hi = 0x8F;
        } else {
            put_unit(out, 0xFFFD); i++; continue;
        }
        size_t k = 1;
        for (; k <= need && i + k < len; k++) {
            unsigned char b = d[i + k];
            unsigned char l = (k == 1) ? lo : 0x80, h = (k == 1) ? hi : 0xBF;
            if (b < l || b > h) break;
        }
        if (k == need + 1) {
            uint32_t cp = c & (need == 1 ? 0x1F : need == 2 ? 0x0F : 0x07);
            for (size_t j = 1; j <= need; j++) cp = (cp << 6) | (d[i + j] & 0x3F);
            if (is_high(cp) || is_low(cp)) put_unit(out, 0xFFFD);
            else put_cp(out, cp);
            i += need + 1;
        } else {
            put_unit(out, 0xFFFD);
            i += k;
        }
    }
}

/* --- decoders ---------------------------------------------------- */

static uint32_t read16(const unsigned char *p, bool be)
{
    return be ? ((uint32_t)p[0] << 8 | p[1]) : ((uint32_t)p[1] << 8 | p[0]);
}

static uint32_t read32(const unsigned char *p, bool be)
{
    return be ? ((uint32_t)p[0] << 24 | (uint32_t)p[1] << 16 | (uint32_t)p[2] << 8 | p[3])
              : ((uint32_t)p[3] << 24 | (uint32_t)p[2] << 16 | (uint32_t)p[1] << 8 | p[0]);
}

/* Java's UTF-16 decoder. Only "UTF-16" reads a byte-order mark. A high
 * surrogate and the unit after it are one malformed input (one U+FFFD)
 * when that unit is not a low surrogate; a lone low surrogate is one
 * U+FFFD; whatever is left at the end, short of a complete character,
 * is one U+FFFD. */
static void utf16_decode(int order, const unsigned char *d, size_t len, units *out)
{
    bool be = order != CS_LE;
    size_t i = 0;
    if (order == CS_DETECT && len >= 2) {
        uint32_t bom = read16(d, true);
        if (bom == 0xFEFF) i = 2;
        else if (bom == 0xFFFE) { be = false; i = 2; }
    }
    while (i + 2 <= len) {
        uint32_t c = read16(d + i, be);
        if (is_high(c)) {
            if (i + 4 > len) break;
            uint32_t c2 = read16(d + i + 2, be);
            if (is_low(c2)) {
                put_unit(out, (uint16_t)c);
                put_unit(out, (uint16_t)c2);
            } else {
                put_unit(out, 0xFFFD);
            }
            i += 4;
        } else if (is_low(c)) {
            put_unit(out, 0xFFFD);
            i += 2;
        } else {
            put_unit(out, (uint16_t)c);
            i += 2;
        }
    }
    if (i < len) put_unit(out, 0xFFFD);
}

/* Java's UTF-32 decoder. Every form drops a leading byte-order mark
 * read in its own byte order; "UTF-32" also takes FF FE 00 00 as a
 * little-endian mark. Code points up to U+10FFFF pass through,
 * surrogates included; anything larger is one U+FFFD per four bytes,
 * and one to three bytes left at the end are one U+FFFD. */
static void utf32_decode(int order, const unsigned char *d, size_t len, units *out)
{
    bool be = order != CS_LE;
    size_t i = 0;
    if (len >= 4) {
        uint32_t first = read32(d, be);
        if (first == 0xFEFF) i = 4;
        else if (order == CS_DETECT && first == 0xFFFE0000u) { be = false; i = 4; }
    }
    for (; i + 4 <= len; i += 4) {
        uint32_t cp = read32(d + i, be);
        if (cp <= 0x10FFFF) put_cp(out, cp);
        else put_unit(out, 0xFFFD);
    }
    if (i < len) put_unit(out, 0xFFFD);
}

uint16_t *cs_decode_units(const cs_charset *cs, const unsigned char *d, size_t len, size_t *n)
{
    units u = { NULL, 0, 0 };
    switch (cs->kind) {
    case CS_UTF8:  utf8_to_units(d, len, &u); break;
    case CS_UTF16: utf16_decode(cs->order, d, len, &u); break;
    case CS_UTF32: utf32_decode(cs->order, d, len, &u); break;
    case CS_ASCII:
        for (size_t i = 0; i < len; i++) put_unit(&u, d[i] < 0x80 ? d[i] : 0xFFFD);
        break;
    case CS_LATIN1:
        for (size_t i = 0; i < len; i++) put_unit(&u, d[i]);
        break;
    case CS_TABLE:
        for (size_t i = 0; i < len; i++) put_unit(&u, d[i] < 0x80 ? d[i] : cs->table[d[i] - 0x80]);
        break;
    }
    *n = u.n;
    return u.u != NULL ? u.u : AUSSOM_ALLOC_ATOMIC(sizeof(uint16_t));
}

char *cs_decode(const cs_charset *cs, const unsigned char *d, size_t len)
{
    size_t n;
    uint16_t *u = cs_decode_units(cs, d, len, &n);
    return av_units_to_text(u, n, NULL);
}

/* --- encoders ---------------------------------------------------- */

typedef struct { unsigned char *b; size_t n, cap; } bytes;

static void put_byte(bytes *b, unsigned char c)
{
    if (b->n == b->cap) {
        size_t cap = b->cap ? b->cap * 2 : 64;
        unsigned char *nb = AUSSOM_ALLOC_ATOMIC(cap);
        if (b->n > 0) memcpy(nb, b->b, b->n);
        b->b = nb;
        b->cap = cap;
    }
    b->b[b->n++] = c;
}

/* The single byte for `cp` in a byte charset, or -1 when it has none. */
static int byte_for(const cs_charset *cs, uint32_t cp)
{
    if (cp < 0x80) return (int)cp;
    switch (cs->kind) {
    case CS_LATIN1: return cp <= 0xFF ? (int)cp : -1;
    case CS_TABLE:
        if (cp == 0xFFFD) return -1;
        for (int i = 0; i < 128; i++) if (cs->table[i] == cp) return 0x80 + i;
        return -1;
    default: return -1;
    }
}

unsigned char *cs_encode_units(const cs_charset *cs, const uint16_t *src, size_t n, size_t *out_len)
{
    units u = { (uint16_t *)src, n, n };
    bytes out = { NULL, 0, 0 };
    bool be = cs->order != CS_LE;
    if (cs->kind == CS_UTF16 && cs->order == CS_DETECT && u.n > 0) {
        put_byte(&out, 0xFE);
        put_byte(&out, 0xFF);
    }
    for (size_t i = 0; i < u.n; i++) {
        uint32_t cp = u.u[i];
        size_t nunits = 1;
        bool lone = false;
        if (is_high(cp) && i + 1 < u.n && is_low(u.u[i + 1])) {
            cp = 0x10000 + ((cp - 0xD800) << 10) + (u.u[i + 1] - 0xDC00);
            nunits = 2;
        } else if (is_high(cp) || is_low(cp)) {
            lone = true;
        }
        switch (cs->kind) {
        case CS_UTF8:
            if (lone) { put_byte(&out, '?'); break; }
            if (cp < 0x80) {
                put_byte(&out, (unsigned char)cp);
            } else if (cp < 0x800) {
                put_byte(&out, (unsigned char)(0xC0 | (cp >> 6)));
                put_byte(&out, (unsigned char)(0x80 | (cp & 0x3F)));
            } else if (cp < 0x10000) {
                put_byte(&out, (unsigned char)(0xE0 | (cp >> 12)));
                put_byte(&out, (unsigned char)(0x80 | ((cp >> 6) & 0x3F)));
                put_byte(&out, (unsigned char)(0x80 | (cp & 0x3F)));
            } else {
                put_byte(&out, (unsigned char)(0xF0 | (cp >> 18)));
                put_byte(&out, (unsigned char)(0x80 | ((cp >> 12) & 0x3F)));
                put_byte(&out, (unsigned char)(0x80 | ((cp >> 6) & 0x3F)));
                put_byte(&out, (unsigned char)(0x80 | (cp & 0x3F)));
            }
            break;
        case CS_UTF16:
            for (size_t k = 0; k < nunits; k++) {
                uint32_t v = lone ? 0xFFFD : u.u[i + k];
                if (be) { put_byte(&out, (unsigned char)(v >> 8)); put_byte(&out, (unsigned char)v); }
                else    { put_byte(&out, (unsigned char)v); put_byte(&out, (unsigned char)(v >> 8)); }
            }
            break;
        case CS_UTF32: {
            uint32_t v = lone ? 0xFFFD : cp;
            unsigned char q[4] = { (unsigned char)(v >> 24), (unsigned char)(v >> 16),
                                   (unsigned char)(v >> 8), (unsigned char)v };
            for (int k = 0; k < 4; k++) put_byte(&out, be ? q[k] : q[3 - k]);
            break;
        }
        default: {
            int b = lone ? -1 : byte_for(cs, cp);
            put_byte(&out, b < 0 ? '?' : (unsigned char)b);
            break;
        }
        }
        i += nunits - 1;
    }
    *out_len = out.n;
    if (out.b == NULL) out.b = AUSSOM_ALLOC_ATOMIC(1);
    return out.b;
}
