/* Text moves through UTF-16 code units, as it does in Java: a decoder
 * turns bytes into units and an encoder turns units into bytes, and
 * Aussom strings hold the same units. */

typedef enum {
    CS_UTF8, CS_ASCII, CS_LATIN1, CS_UTF16, CS_UTF32, CS_TABLE
} cs_kind;

/* Byte order for UTF-16 and UTF-32. CS_DETECT reads a byte-order mark
 * and defaults to big-endian. */
enum { CS_DETECT, CS_BE, CS_LE };

struct cs_charset {
    cs_kind kind;
    int order;                  /* CS_UTF16 / CS_UTF32 */
    const uint16_t *table;      /* CS_TABLE: bytes 0x80-0xFF */
    const char *const *names;   /* canonical name and aliases, upper case */
};

